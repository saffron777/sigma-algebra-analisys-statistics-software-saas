"""Whole-database copy on any SQL engine: plain records out of one database, into another (ids preserved)."""

from __future__ import annotations

import json
from collections.abc import Iterable, Iterator
from pathlib import Path
from typing import Any

from sqlalchemy import delete, func, insert, select, text
from sqlalchemy.engine import Connection

from sigma.domain.notebooks import NOTEBOOK_ID_PATTERN
from sigma.infrastructure.persistence import notebook_format as nbf
from sigma.infrastructure.persistence.sql import schema, table_io
from sigma.infrastructure.persistence.sql.engine import Database
from sigma.infrastructure.persistence.sql.import_draft_store import CHUNK_BYTES

_TABLES = {
    "users": schema.users,
    "app_settings": schema.app_settings,
    "report_templates": schema.report_templates,
    "datasets": schema.datasets,
    "saved_results": schema.saved_results,
    "workspace": schema.workspace,
    "sync_state": schema.sync_state,
    "import_drafts": schema.import_drafts,
    "ai_usage": schema.ai_usage,
    "notebooks": schema.notebooks,
}
_IDENTITY_TABLES = ("users", "ai_usage")  # integer ids generated by the server: copied with their values
_CLEAR_ORDER = (
    "ai_usage",
    "import_drafts",  # its files go with it (ON DELETE CASCADE, removed explicitly too)
    "notebooks",
    "sync_state",
    "workspace",
    "saved_results",
    "datasets",
    "report_templates",
    "app_settings",
    "users",
)
_BATCH_ROWS = 200
_BATCH_BYTES = 4 * 1024 * 1024
_STAGED_RESET = {
    "staged_table": None,
    "n_rows": None,
    "n_cols": None,
    "dtypes": None,
    "columns_info": None,
    "col_map": None,
    "detected": "{}",
    "suggested_name": None,
}


def _size(row: dict[str, Any]) -> int:
    return sum(len(v) for v in row.values() if isinstance(v, str | bytes | bytearray)) + 64


def _batches(rows: Iterable[dict[str, Any]]) -> Iterator[list[dict[str, Any]]]:
    """Groups of rows small enough to send in one statement, whatever the size of their text/binary columns."""
    batch: list[dict[str, Any]] = []
    weight = 0
    for row in rows:
        batch.append(row)
        weight += _size(row)
        if len(batch) >= _BATCH_ROWS or weight >= _BATCH_BYTES:
            yield batch
            batch, weight = [], 0
    if batch:
        yield batch


class SqlTransfer:
    """``files`` tells where notebooks live: ``.ipynb`` files under ``notebooks_root/<user id>/`` (SQLite) or rows."""

    def __init__(self, database: Database, notebooks_root: Path, files: bool) -> None:
        self._db = database
        self._root = Path(notebooks_root)
        self._files = files
        self._written_files: list[Path] = []

    # ------------------------------------------------------------------ inspection
    def counts(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        with self._db.begin() as conn:
            for key, table in _TABLES.items():
                if key == "notebooks" and self._files:
                    counts[key] = sum(1 for _ in self._notebook_files())
                else:
                    counts[key] = int(conn.execute(select(func.count()).select_from(table)).scalar_one())
        return counts

    def is_empty(self) -> bool:
        return not any(self.counts().values())

    # ------------------------------------------------------------------ reading
    def read(self, entity: str) -> Iterator[dict[str, Any]]:
        if entity == "datasets":
            yield from self._read_datasets()
        elif entity == "import_drafts":
            yield from self._read_drafts()
        elif entity == "notebooks" and self._files:
            yield from self._read_notebook_files()
        else:
            with self._db.begin() as conn:
                for row in conn.execute(select(_TABLES[entity])).mappings():
                    yield dict(row)

    def _read_datasets(self) -> Iterator[dict[str, Any]]:
        table = schema.datasets
        with self._db.begin() as conn:
            rows = conn.execute(select(table).order_by(table.c.created_at, table.c.id)).mappings().all()
        for row in rows:
            record = dict(row)
            dtypes = json.loads(record["dtypes"])
            col_map = json.loads(record["col_map"]) if record["col_map"] else None
            with self._db.begin() as conn:
                frame = table_io.read_frame(conn, record.pop("table_name"), list(dtypes), col_map, dtypes)
            record.pop("col_map")
            record["frame"] = frame
            yield record

    def _read_drafts(self) -> Iterator[dict[str, Any]]:
        drafts, files = schema.import_drafts, schema.import_draft_files
        with self._db.begin() as conn:
            rows = [dict(r) for r in conn.execute(select(drafts)).mappings()]
        for record in rows:
            with self._db.begin() as conn:
                chunks = conn.execute(
                    select(files.c.data).where(files.c.draft_id == record["id"]).order_by(files.c.seq)
                ).all()
            record["file"] = b"".join(bytes(c.data) for c in chunks) if chunks else None
            yield record

    def _notebook_files(self) -> Iterator[Path]:
        if not self._root.is_dir():
            return
        for folder in sorted(self._root.iterdir()):
            if folder.is_dir() and folder.name.isdigit():
                for path in sorted(folder.glob("*.ipynb")):
                    if NOTEBOOK_ID_PATTERN.match(path.stem):
                        yield path

    def _read_notebook_files(self) -> Iterator[dict[str, Any]]:
        for path in self._notebook_files():
            try:
                content = path.read_text(encoding="utf-8")
                notebook = json.loads(content)
            except (OSError, ValueError):
                continue  # a broken file is reported as skipped, the rest still migrate
            meta = notebook.get("metadata", {}).get("sigma", {})
            modified = nbf.iso_from_timestamp(path.stat().st_mtime)
            yield {
                "id": path.stem,
                "user_id": int(path.parent.name),
                "name": str(meta.get("name") or path.stem)[:120],
                "n_cells": len(notebook.get("cells", [])),
                "created_at": meta.get("created_at") or modified,
                "updated_at": modified,
                "revision": 1,
                "content": content,
            }

    # ------------------------------------------------------------------ writing
    def write(self, entity: str, records: Iterable[dict[str, Any]]) -> int:
        if entity == "datasets":
            return self._write_datasets(records)
        if entity == "import_drafts":
            return self._write_drafts(records)
        if entity == "notebooks" and self._files:
            return self._write_notebook_files(records)
        if entity == "notebooks":
            records = self._known_owners(records)
        return self._write_rows(_TABLES[entity], entity, records)

    def _write_rows(self, table: Any, entity: str, records: Iterable[dict[str, Any]]) -> int:
        count = 0
        for batch in _batches(records):
            with self._db.begin() as conn, self._identity_insert(conn, entity):
                conn.execute(insert(table), batch)
            count += len(batch)
        return count

    def _write_datasets(self, records: Iterable[dict[str, Any]]) -> int:
        count = 0
        for record in records:
            frame = record.pop("frame")
            table_name = table_io.new_table_name("ds")
            with self._db.begin() as conn:
                col_map = table_io.write_frame(conn, table_name, frame)
                conn.execute(
                    insert(schema.datasets).values(**record, table_name=table_name, col_map=json.dumps(col_map))
                )
            count += 1
        return count

    def _write_drafts(self, records: Iterable[dict[str, Any]]) -> int:
        count = 0
        for record in records:
            content = record.pop("file")
            row = {**record, **_STAGED_RESET}  # parsed previews are rebuilt from the file on demand
            with self._db.begin() as conn:
                conn.execute(insert(schema.import_drafts).values(**row))
                if content is not None:
                    for seq, start in enumerate(range(0, max(len(content), 1), CHUNK_BYTES)):
                        conn.execute(
                            insert(schema.import_draft_files).values(
                                draft_id=row["id"], seq=seq, data=content[start : start + CHUNK_BYTES]
                            )
                        )
            count += 1
        return count

    def _known_owners(self, records: Iterable[dict[str, Any]]) -> Iterator[dict[str, Any]]:
        with self._db.begin() as conn:
            owners = {r.id for r in conn.execute(select(schema.users.c.id))}
        for record in records:
            if record["user_id"] in owners:  # a notebook folder of a deleted account has nobody to belong to
                yield record

    def _write_notebook_files(self, records: Iterable[dict[str, Any]]) -> int:
        owners = {r.id for r in self._rows(select(schema.users.c.id))}
        count = 0
        for record in records:
            if record["user_id"] not in owners:
                continue
            folder = self._root / str(record["user_id"])
            folder.mkdir(parents=True, exist_ok=True)
            target = folder / f"{record['id']}.ipynb"
            target.write_text(record["content"], encoding="utf-8")
            self._written_files.append(target)
            count += 1
        return count

    def _rows(self, statement: Any) -> list[Any]:
        with self._db.begin() as conn:
            return list(conn.execute(statement))

    def _identity_insert(self, conn: Connection, entity: str) -> Any:
        return _IdentityInsert(conn, entity, self._db) if entity in _IDENTITY_TABLES else _Nothing()

    # ------------------------------------------------------------------ after the copy
    def finish(self) -> None:
        """Make the servers' own id generators continue after the copied ids."""
        dialect = self._db.dialect
        if dialect not in ("postgresql", "oracle"):
            return  # SQL Server, MySQL and SQLite adjust their counters when explicit ids are inserted
        with self._db.begin() as conn:
            for name in _IDENTITY_TABLES:
                if dialect == "postgresql":
                    table = self._qualified(name)
                    sequence = f"pg_get_serial_sequence('{table}', 'id')"
                    conn.execute(
                        text(f"SELECT setval({sequence}, COALESCE((SELECT MAX(id) FROM {table}), 0) + 1, false)")
                    )
                else:
                    conn.execute(
                        text(
                            f"ALTER TABLE {name} MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))"
                        )
                    )

    def _qualified(self, name: str) -> str:
        schema_name = self._db.settings.schema
        return f'"{schema_name}"."{name}"' if schema_name else f'"{name}"'

    def clear(self) -> None:
        """Empty what ``write`` filled (only ever called on a target that was empty when the migration began)."""
        with self._db.begin() as conn:
            tables = [row.table_name for row in conn.execute(select(schema.datasets.c.table_name))]
            for name in tables:  # read them all first: SQLite cannot drop a table while a cursor is reading another
                table_io.drop_table(conn, name)
            for key in _CLEAR_ORDER:
                if key == "import_drafts":
                    conn.execute(delete(schema.import_draft_files))
                conn.execute(delete(_TABLES[key]))
        for path in self._written_files:
            path.unlink(missing_ok=True)
        self._written_files.clear()


class _Nothing:
    def __enter__(self) -> None:
        return None

    def __exit__(self, *exc: object) -> None:
        return None


class _IdentityInsert:
    """``SET IDENTITY_INSERT … ON`` around explicit ids on SQL Server (other engines accept them as they are)."""

    def __init__(self, conn: Connection, table: str, database: Database) -> None:
        self._conn = conn
        self._active = database.dialect == "mssql"
        prefix = f"[{database.settings.schema}]." if database.settings.schema else ""
        self._target = f"{prefix}[{table}]"

    def __enter__(self) -> None:
        if self._active:
            self._conn.execute(text(f"SET IDENTITY_INSERT {self._target} ON"))

    def __exit__(self, *exc: object) -> None:
        if self._active:
            self._conn.execute(text(f"SET IDENTITY_INSERT {self._target} OFF"))
